let lang = "en";
try {
  const saved = localStorage.getItem("cc_lang");
  if (saved === "sw" || saved === "en") lang = saved;
  else if ((navigator.language || "").toLowerCase().startsWith("sw")) lang = "sw";
} catch {
  /* storage blocked: keep English */
}

export const getLang = () => lang;

export function setLang(next) {
  lang = next === "sw" ? "sw" : "en";
  try {
    localStorage.setItem("cc_lang", lang);
  } catch {
    /* ignore */
  }
}

export const t = (key) => strings[lang][key] ?? strings.en[key] ?? key;
export const cropName = (key) => strings[lang].crops[key] ?? strings.en.crops[key] ?? key;
export const cropKeys = Object.keys(strings.en.crops);
